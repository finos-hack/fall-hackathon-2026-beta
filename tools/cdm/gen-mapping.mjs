// Writes docs/cdm-mapping.md from the mapping table in core/lib/cdm.mjs, so the document and the code cannot drift.
// node tools/cdm/gen-mapping.mjs           writes the file
// node tools/cdm/gen-mapping.mjs --check   exits 1 if the file is out of date (test/node/docs.test.mjs runs this)
import { readFileSync, writeFileSync } from 'node:fs';
import path from 'node:path';
import { pathToFileURL } from 'node:url';
import { MAPPING, CDM_VERSION, CDM_TYPE } from '../../core/lib/cdm.mjs';
import { ROOT } from '../../core/lib/paths.mjs';

export const FILE = path.join(ROOT, 'docs', 'cdm-mapping.md');

export function render() {
  const rows = MAPPING.map(([p, rule]) => `| \`${p}\` | ${rule} |`).join('\n');
  return `# CDM mapping

<!-- Generated by tools/cdm/gen-mapping.mjs from core/lib/cdm.mjs. Do not edit by hand. -->

Interlock describes token movements and settlements in the [FINOS Common Domain Model](https://github.com/finos/common-domain-model), version **${CDM_VERSION}**, as a \`${CDM_TYPE}\`. Every object Interlock produces is validated with CDM's own tooling: the \`finos-cdm\` ${CDM_VERSION} Python package (attribute types and Rune conditions), by \`tools/cdm/validate.py\`, in CI.

## Directions

- **In: a CDM instruction drives settlement.** A \`TransferInstruction\` with two legs, status \`Instructed\` (delivery first, then payment), is read by \`parseTransferInstruction\` and settled by the \`settle\` action through \`DvPSettlement\`.
- **Out: the answer, and every movement.** The same instruction comes back with each leg \`Settled\` and the settling transaction hash. Each recorded issuance, transfer, redemption and forced transfer is also exported as a one-leg \`TransferInstruction\`, \`Settled\`.
- CDM does not drive issuance or templates in this round (issue #5, decision D-B).

## Mapping rules

| CDM path | Rule |
|---|---|
${rows}

Issuance is paid by the token's issuer to the holder, and redemption by the holder to the issuer.

## Example

The settled answer of story D (Bob sells Alice 100 dMMF for 100 dDEP) has this shape. \`test/fixtures/cdm/dvp-settled.shape.json\` pins it, with addresses, hashes and dates as placeholders.

\`\`\`json
${readFileSync(path.join(ROOT, 'test', 'fixtures', 'cdm', 'dvp-settled.shape.json'), 'utf8').trim()}
\`\`\`

## What is not mapped

- A CDM \`BusinessEvent\` and the trade lifecycle (\`TradeState\`): a \`BusinessEvent\` needs a \`before\` trade state, that is a full CDM trade, which is out of scope here. Interlock uses the \`TransferInstruction\` primitive directly.
- Products: templates are not generated from, or exported to, CDM products.
- Prices, fees, cash in a currency: dDEP is a tokenized deposit, mapped as a \`DigitalAsset\` (CDM's \`Cash\` requires a currency code and models money, not a token).

## Findings for the CDM maintainers

Found while validating with \`finos-cdm\` ${CDM_VERSION} (Python). Both have workarounds in \`tools/cdm/validate.py\`:

1. The package must be imported through \`finos._bundle\` first; importing a model module directly (for example \`PartyReferencePayerReceiver\`) fails on a circular import.
2. The bundle declares 318 fields as \`None\` and re-types them later; validators built before that (seen on \`PrimitiveInstruction.transfer\` and \`Identifier.assignedIdentifier\`) reject valid input with "Input should be None" until every model is rebuilt with \`model_rebuild(force=True)\`.
3. Optional reference fields (\`payerAccountReference\`, \`receiverAccountReference\`, \`Identifier.issuerReference\`) are rejected when absent ("Expected ... or dict but got NoneType"); Interlock always sets the accounts (the wallet), and sets \`issuer\` rather than \`issuerReference\` on identifiers, as CDM's \`IssuerChoice\` condition allows.
`;
}

if (import.meta.url === pathToFileURL(process.argv[1] ?? '').href) {
  const text = render();
  if (process.argv.includes('--check')) {
    const current = readFileSync(FILE, 'utf8');
    if (current !== text) {
      console.error('docs/cdm-mapping.md is out of date: run node tools/cdm/gen-mapping.mjs');
      process.exit(1);
    }
  } else {
    writeFileSync(FILE, text);
    console.log('wrote docs/cdm-mapping.md');
  }
}
